"""终端工具领域异常与稳定错误码。"""

from enum import Enum

from tools.exceptions import ToolError


class TerminalErrorCode(str, Enum):
    INVALID_ARGUMENT = "TERMINAL_INVALID_ARGUMENT"
    UNSUPPORTED_PLATFORM = "TERMINAL_UNSUPPORTED_PLATFORM"
    WORKSPACE_ERROR = "TERMINAL_WORKSPACE_ERROR"
    APPROVAL_REQUIRED = "TERMINAL_APPROVAL_REQUIRED"
    DENIED = "TERMINAL_DENIED"
    PROCESS_START_FAILED = "TERMINAL_PROCESS_START_FAILED"
    TIMEOUT = "TERMINAL_TIMEOUT"
    OUTPUT_LIMIT = "TERMINAL_OUTPUT_LIMIT"
    RESOURCE_LIMIT = "TERMINAL_RESOURCE_LIMIT"
    CANCELLED = "TERMINAL_CANCELLED"


class TerminalToolError(ToolError):
    """终端工具共享一个异常类型，具体失败原因由错误码表达。"""
